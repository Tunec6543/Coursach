class Command(BaseCommand):
    help = 'Загружает демонстрационные ингредиенты и рецепты. Повторный запуск безопасен.'

    @transaction.atomic
    def handle(self, *args, **options):
        ingredients = {}
        for name, (unit, category) in INGREDIENTS.items():
            obj, _ = Ingredient.objects.get_or_create(
                name=name,
                defaults={'unit': unit, 'category': category},
            )
            ingredients[name] = obj

        created_count = 0
        for data in RECIPES:
            recipe, created = Recipe.objects.get_or_create(
                title=data['title'],
                defaults={
                    'description': data['description'],
                    'instructions': data['instructions'],
                    'prep_time': data['prep_time'],
                    'servings': data['servings'],
                },
            )
            if not created:
                continue
            for name, quantity in data['items']:
                RecipeIngredient.objects.create(
                    recipe=recipe,
                    ingredient=ingredients[name],
                    quantity=quantity,
                )
            created_count += 1

        self.stdout.write(self.style.SUCCESS(
            f'Новых рецептов: {created_count} из {len(RECIPES)}.'
        ))
